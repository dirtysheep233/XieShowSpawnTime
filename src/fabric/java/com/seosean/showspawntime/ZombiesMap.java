    private final int[][] timer;
    private final int maxRound;
 
    ZombiesMap(int[][] timer, int maxRound) {
        this.timer = timer;
        this.maxRound = maxRound;
    }
 
    public int[][] timer() {
        return timer;
    }
 
    public int maxRound() {
        return maxRound;
    }
 
    public int[] roundTimes(int round) {
        if (round < 1) {
            return new int[0];
        }
        if (this == DARK_DUNGEON) {
            int cycleRound = ((round - 1) % 30) + 1;
            if (cycleRound > timer.length) {
                return new int[0];
            }
            return timer[cycleRound - 1].clone();
        }
        if (round > timer.length) {
            return new int[0];
        }
        return timer[round - 1].clone();
    }
 
    public static ZombiesMap detect(MinecraftClient client, ScoreboardSnapshot scoreboard) {
        String joined = String.join(" ", scoreboard.lines()).toLowerCase();
        if (joined.contains("dark") || joined.contains("dungeon") || joined.contains("黑暗") || joined.contains("地牢")) {
            return DARK_DUNGEON;
        }
        if (joined.contains("cursed") || joined.contains("cave") || joined.contains("诅咒") || joined.contains("洞穴")) {
            return CURSED_CAVE;
        }
        if (joined.contains("portal") || joined.contains("lab") || joined.contains("传送门") || joined.contains("实验室")) {
            return PORTAL_LAB;
        }
        return NULL;
    }
